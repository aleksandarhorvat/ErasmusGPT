"""Write eval/report/smoke.md: 10 home courses x 4 strategies, for eyeballing (S3-A3).

    python eval/make_smoke.py [--host-programme utwente-tcs-bsc]

Not a measurement. It exists so an obvious regression (a strategy returning nonsense, a
strategy returning the same list as another) is visible before the gold set exists.
The numbers that count come from eval/run_eval.py in stage 5.
"""
from __future__ import annotations

import argparse
import sys
import time
from datetime import UTC, datetime
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "backend"))

from app.core.config import get_settings  # noqa: E402
from app.ingest.loader import CurriculumStore  # noqa: E402
from app.matching.interface import STRATEGIES  # noqa: E402
from app.matching.pipeline import PipelineMatcher  # noqa: E402

OUT = REPO_ROOT / "eval" / "report" / "smoke.md"

# One per part of the curriculum: programming, theory, systems, data, applications.
SAMPLE_CODES = [
    "I011", "I021", "I031", "I051", "I142",
    "I151", "I152", "I243", "I251", "I263",
]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--home-programme", default="uns-pmf-informatics-bsc")
    parser.add_argument("--host-programme", default="utwente-tcs-bsc")
    parser.add_argument("--top-k", type=int, default=3)
    args = parser.parse_args()

    settings = get_settings()
    store = CurriculumStore(settings.curricula_dir)
    matcher = PipelineMatcher(store, settings)

    homes = [c for c in store.get_courses(args.home_programme) if c.code in SAMPLE_CODES]
    host = store.get_programme(args.host_programme)

    lines = [
        "# Smoke sheet (S3-A3)",
        "",
        f"Generated by `eval/make_smoke.py` on {datetime.now(UTC):%Y-%m-%d}. "
        f"Top {args.top_k} per strategy, percentages as the UI would show them.",
        "",
        f"- Home: `{args.home_programme}`, {len(homes)} of "
        f"{len(store.get_courses(args.home_programme))} courses sampled",
        f"- Host: `{args.host_programme}`, {len(host.courses)} courses, "
        f"{host.raw.get('academic_year')}",
        f"- Bi-encoder `{settings.bi_encoder_repo}`, cross-encoder "
        f"`{settings.cross_encoder_repo}`, CPU",
        "",
        "Read it as: does rank 1 look right, and do the four strategies differ?",
        "",
    ]

    timings: dict[str, float] = {}
    for home in homes:
        lines += [f"## {home.code} {home.title}", ""]
        for strategy in STRATEGIES:
            started = time.perf_counter()
            candidates = matcher.match_course(
                home.course_uid, args.host_programme, strategy, args.top_k
            )
            elapsed = (time.perf_counter() - started) * 1000
            timings[strategy] = timings.get(strategy, 0.0) + elapsed
            listed = " | ".join(
                f"{c.host_course.title} ({c.score_pct} %)" for c in candidates
            )
            lines.append(f"- `{strategy}` ({elapsed:.0f} ms): {listed}")
        best = matcher.match_course(home.course_uid, args.host_programme, "hybrid+ce", 1)
        evidence = best[0].evidence if best else None
        if evidence:
            lines += [
                "",
                f"  Evidence for rank 1 (similarity {evidence.similarity}):",
                f"  - home: {evidence.home_sentence}",
                f"  - host: {evidence.host_sentence}",
            ]
        lines.append("")

    lines += [
        "## How to read the percentages",
        "",
        "Compare ranks, not percentages, across strategies. Each strategy's score comes",
        "from a different scale and the display mapping is a placeholder until S3-B1:",
        "BM25 and hybrid are shown relative to the best hit for the same home course, so",
        "rank 1 always reads 100 %, and the cross-encoder emits low absolute values",
        "because it was trained on search relevance, not on course equivalence.",
        "",
        "## Mean latency per query",
        "",
        "| Strategy | ms |",
        "|---|---|",
    ]
    lines += [
        f"| `{strategy}` | {total / len(homes):.0f} |"
        for strategy, total in timings.items()
    ]
    lines.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO_ROOT)} ({len(homes)} home courses)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
