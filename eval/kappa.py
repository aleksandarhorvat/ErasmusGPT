"""Inter-annotator agreement on the cold slice. Stage 5, tasks S5-B1 and S5-A3.

Person B labels about 30 pooled pairs cold, into data/gold/gold_pairs_b.csv, without
seeing the model's labels or Person A's corrections. All 30 sit in Person A's half of
the split pool, so this script compares B's cold labels with A's checked labels in the
merged gold_pairs.csv.

    python eval/kappa.py

Writes eval/report/kappa.md. Reports unweighted Cohen's kappa, which treats 0, 1 and 2
as unordered, and linearly weighted kappa, which counts a 1-against-2 disagreement as
half as bad as a 0-against-2 one. The labels are ordinal, so the weighted figure is the
headline and the unweighted one is there for comparison with other work.

Only pairs labelled by both people count. Rows Person A has not checked yet are left
out and counted, so a kappa computed halfway through the labelling pass says so.
"""
from __future__ import annotations

import argparse
import csv
import sys
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "eval"))
GOLD_A = REPO_ROOT / "data" / "gold" / "gold_pairs.csv"
GOLD_B = REPO_ROOT / "data" / "gold" / "gold_pairs_b.csv"
PRELABELS = REPO_ROOT / "data" / "gold" / "llm_prelabels.csv"
CATEGORIES = (0, 1, 2)

Pair = tuple[str, str]


def cohen_kappa(first: list[int], second: list[int], weighted: bool = False,
                categories: tuple[int, ...] = CATEGORIES) -> float:
    """Cohen's kappa between two raters over the same items.

    With `weighted`, a disagreement costs |i - j| / (k - 1) (linear weights). Returns
    1.0 when both raters use one identical category throughout, where kappa is
    undefined but agreement is perfect, and 0.0 for no items.
    """
    if len(first) != len(second):
        raise ValueError("both raters must label the same items")
    n = len(first)
    if n == 0:
        return 0.0
    span = max(categories) - min(categories) or 1

    def cost(i: int, j: int) -> float:
        if weighted:
            return abs(i - j) / span
        return 0.0 if i == j else 1.0

    observed = sum(cost(i, j) for i, j in zip(first, second, strict=True)) / n
    margin_a, margin_b = Counter(first), Counter(second)
    expected = sum(
        margin_a[i] * margin_b[j] * cost(i, j) for i in categories for j in categories
    ) / (n * n)
    if expected == 0:
        return 1.0
    return 1.0 - observed / expected


def read_labels(path: Path, label_column: str = "label",
                checked_only: bool = False) -> dict[Pair, int]:
    """(home_uid, host_uid) -> label, skipping empty labels."""
    labels: dict[Pair, int] = {}
    if not path.exists():
        return labels
    with path.open(encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            if checked_only and row.get("checked", "").strip().lower() != "yes":
                continue
            value = row.get(label_column, "").strip()
            if value:
                labels[(row["home_uid"], row["host_uid"])] = int(value)
    return labels


def agreement_row(name: str, first: list[int], second: list[int]) -> str:
    same = sum(x == y for x, y in zip(first, second, strict=True))
    return (
        f"| {name} | {len(first)} | {same / len(first):.2f} | "
        f"{cohen_kappa(first, second):.2f} | "
        f"{cohen_kappa(first, second, weighted=True):.2f} |"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default="eval/report/kappa.md")
    args = parser.parse_args()

    slice_b = read_labels(GOLD_B)
    if not slice_b:
        print("gold_pairs_b.csv has no labels yet: S5-B1 is still open")
        return 1
    labels_a = read_labels(GOLD_A, checked_only=True)
    machine = read_labels(PRELABELS, label_column="llm_label")

    shared = sorted(pair for pair in slice_b if pair in labels_a)
    waiting = len(slice_b) - len(shared)
    if not shared:
        print(f"none of the {len(slice_b)} cold pairs is checked in gold_pairs.csv yet")
        return 1

    from provenance import claude_labels

    second = claude_labels()
    model_made = {pair for pair, (_, final) in second.items() if final}
    by_luka = [pair for pair in shared if pair not in model_made]
    a = [labels_a[pair] for pair in shared]
    b = [slice_b[pair] for pair in shared]
    lines = [
        "# Inter-annotator agreement",
        "",
        f"Generated by `eval/kappa.py` on {datetime.now(UTC):%Y-%m-%d}. Aleksandar labelled",
        "the 30 pairs cold, before his own half. The A half of the gold set holds these",
        "pairs; where Luka did not check them himself, their label is Claude's (a second",
        "model, blind to the pre-labels), so each annotator gets their own row below.",
        "",
        "| Comparison | Pairs | Raw agreement | Cohen's kappa | Weighted kappa (linear) |",
        "|---|---|---|---|---|",
    ]
    if by_luka:
        lines.append(agreement_row("Luka (human) vs Aleksandar (human)",
                                   [labels_a[p] for p in by_luka],
                                   [slice_b[p] for p in by_luka]))
    with_claude = [pair for pair in shared if pair in second]
    if with_claude:
        lines.append(agreement_row("Claude (model) vs Aleksandar (human)",
                                   [second[p][0] for p in with_claude],
                                   [slice_b[p] for p in with_claude]))
    lines.append(agreement_row("Gold set as merged vs Aleksandar", a, b))
    with_model = [pair for pair in shared if pair in machine]
    if with_model:
        lines.append(agreement_row("Aleksandar vs model pre-label",
                                   [slice_b[p] for p in with_model],
                                   [machine[p] for p in with_model]))
        if with_claude:
            both = [p for p in with_model if p in second]
            lines.append(agreement_row("Claude vs model pre-label",
                                       [second[p][0] for p in both],
                                       [machine[p] for p in both]))

    confusion = Counter(zip(a, b, strict=True))
    lines += [
        "",
        "Confusion, rows the merged gold set and columns Aleksandar:",
        "",
        "| A / B | 0 | 1 | 2 |",
        "|---|---|---|---|",
    ]
    for i in CATEGORIES:
        cells = " | ".join(str(confusion[(i, j)]) for j in CATEGORIES)
        lines.append(f"| {i} | {cells} |")
    lines += [
        "",
        "Aleksandar against the pre-label is the control: he never saw them, so that row",
        "measures how far an unanchored human sits from the model. Claude against",
        "Aleksandar is the figure to quote for the model-labelled rows of the gold set.",
    ]
    if waiting:
        lines += ["", f"Partial figure: {waiting} cold pairs are still unchecked in "
                  "`gold_pairs.csv`."]
    out = REPO_ROOT / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"kappa over {len(shared)} pairs -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
